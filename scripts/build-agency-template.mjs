#!/usr/bin/env node
// Regenerate both shipped representations from the editable, reusable vault.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const target = join(root, 'templates/lead-gen-agency.company-template.json');
const fallback = join(root, 'integrations/bizos-local/runtime/src/harness/template-lead-gen-agency.ts');
const template = JSON.parse(readFileSync(target, 'utf8'));
const folders = new Set(template.folders);
const notes = [];
function walk(prefix = '') {
  for (const entry of readdirSync(join(root, 'vault', prefix), { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const path = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isSymbolicLink()) throw new Error(`Symlink refused: ${path}`);
    if (entry.isDirectory()) { folders.add(path); walk(path); }
    else if (entry.isFile() && path.endsWith('.md')) notes.push({ path, text: readFileSync(join(root, 'vault', path), 'utf8') });
  }
}
walk();
template.folders = [...folders].sort();
template.notes = notes;
const serialized = JSON.stringify(template, null, 2);
const files = new Map([
  [target, `${serialized}\n`],
  [fallback, '// Generated by scripts/build-agency-template.mjs from the MIT Agency data pack.\n// This runtime module retains AGPL-3.0-only; embedded documents retain their MIT notices.\n// The runtime prefers the staged kit (including skills); this fallback must never drift.\nimport type { CompanyTemplate } from "./company-os.js";\n\nexport const LEAD_GEN_AGENCY: CompanyTemplate = ' + serialized + ';\n'],
]);
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('usage: node scripts/build-agency-template.mjs [--check]');
for (const [file, content] of files) {
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== content) throw new Error(`stale generated template: ${file}`);
  } else writeFileSync(file, content);
}
console.log(`Agency: ${notes.length} notes, ${template.bots.length} source roles, no routines enabled.`);
