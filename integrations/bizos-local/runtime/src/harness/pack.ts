// A business pack inside Local BizOS: the LeadFactory agency (`agency.ts`)
// and the E-commerce store (`ecommerce.ts`), on ONE frame.
//
// A pack is a catalogue template (its notes, its agents, its team) plus a
// cockpit: the kit's own `createApp`, bound to `127.0.0.1` on an ephemeral
// port, its store INSIDE the bound vault (`Apps/<Pack>/data`). The template
// is installed by the generic installer (`harness.templates`, through the
// workspace binding) — a pack creates no agent of its own and never a second
// team; it attaches its cockpit and its tools to the bots the installation
// recorded. There is no second store and nothing writes `db.json` behind the
// cockpit's back.
//
// What a pack guards:
//   - the cockpit's service credential: random, in memory, for this process
//     only, in the `Authorization` header of the service's own requests and
//     nowhere else — not a URL, a tool result, an error, a note, an agent's
//     environment. A person gets in with a one-use ticket (`open()`); the
//     desktop embeds the page and never sees the credential;
//   - the tools: served to the pack's own bots only, under the run's
//     capability, re-checked on entry, before every write and before a
//     result leaves; a STOP aborts what is in flight (`abortRun`) before the
//     CLI has settled. What the cockpit already accepted is not undone;
//   - the vault: the data folder is refused through a symlink, the Markdown
//     dossiers (`Clients/<id>/Dossier.md`, `Products/<id>/Dossier.md`) are
//     generated views rewritten only when they carry the generated marker,
//     and no credential is ever mirrored (the cockpit's `connections.json`
//     stays in its data folder, which no read tool reaches).
